import fs from 'node:fs';
import path from 'node:path';

import type { ModData } from '~/data/schema/mod-data';
import type { ModHash } from '~/data/schema/mod-hash';
import { emptyModHash, updateHash } from '~/utils/hash';

const source = process.argv[2];
if (!source)
  throw new Error('Pass the data builder dist/calculator directory.');
const destination = 'public/data/aef';
const assets = [
  'data.json',
  'transfer.json',
  'icons.webp',
  ...['zh', 'ja', 'ru'].map((lang) => `i18n/${lang}.json`),
];
const files = assets.map((file) => ({
  file,
  content: fs.readFileSync(path.join(source, file)),
}));
const data = JSON.parse(files[0].content.toString()) as ModData;
if (data.endfield?.schemaVersion !== 1)
  throw new Error('Unsupported Endfield data schema.');
const transfer = JSON.parse(files[1].content.toString()) as {
  schemaVersion?: number;
};
if (transfer.schemaVersion !== 1)
  throw new Error('Unsupported transfer data schema.');
if (data.recipes.some((recipe) => recipe.category === '__domain_transfer'))
  throw new Error('Transfer recipes must be generated by the calculator.');
const hash = JSON.parse(
  fs.readFileSync(path.join(destination, 'hash.json'), 'utf8'),
) as ModHash;
const current = emptyModHash();
updateHash(data, current);
// Append new IDs before updating the catalog. A retired ID's index must never
// be assigned to a different item in an existing shared link.
for (const key of Object.keys(current) as (keyof ModHash)[]) {
  const slots = new Set(hash[key]);
  for (const id of current[key])
    if (id != null && !slots.has(id)) hash[key].push(id);
}
updateHash(data, hash);
for (const { file, content } of files)
  fs.writeFileSync(path.join(destination, file), content);
fs.writeFileSync(path.join(destination, 'hash.json'), JSON.stringify(hash));
